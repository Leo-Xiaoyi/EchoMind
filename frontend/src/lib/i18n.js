export function setLocale(value) {
  if (!SUPPORTED_LOCALES.includes(value)) return false
  locale.value = value
  applyDocumentLocale()
  return true
}

export function getLocale() {
  return locale.value
}

export function t(key, params = {}) {
  const dictionary = messages[locale.value] || messages[DEFAULT_LOCALE]
  const text = dictionary[key] ?? messages[DEFAULT_LOCALE][key] ?? key
  return String(text).replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match)
}

export function applyDocumentLocale() {
  if (typeof document === 'undefined') return
  document.documentElement.lang = locale.value
  document.title = t('app.title')
}

export function formatNumber(value) {
  try {
    return new Intl.NumberFormat(locale.value).format(Number(value || 0))
  } catch {
    return String(value || 0)
  }
}

export function messageCountLabel(count) {
  const key = count === 1 ? 'chat.messageCountOne' : 'chat.messageCountMany'
  return t(key, { count: formatNumber(count) })
}

export function attemptsLabel(count) {
  const key = count === 1 ? 'evaluation.attemptsOne' : 'evaluation.attemptsMany'
  return t(key, { count: formatNumber(count) })
}

